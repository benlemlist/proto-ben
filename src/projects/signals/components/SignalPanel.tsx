// Signal side panel (prod WatchListSignalPanel): company header, agent, "Signal details" (per type, from the
// Notion "Side panel data"), contact + company data, actions. Forecast signals get the heat score + "Why this company".
import { SidePanel, SidePanelContent, ModalHeader, ModalTitle, ModalBody, ModalFooter, Button, Avatar, Badge, BadgeSpecific } from "@l3mpire/ui";
import { Icon, faLinkedinBrand, faGlobeOutline } from "@l3mpire/icons";
import { fa, signalType } from "../data";
import { detailRows, relTime, initials } from "../logic";
import { useSig } from "../store";
import { Section, Heat, Muted } from "./ui";

function Row({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="flex flex-col gap-xs">
      <Muted>{label}</Muted>
      <div className="text-base leading-base text-[var(--core-text-main-primary)]">{children}</div>
    </div>
  );
}

export function SignalPanel() {
  const s = useSig();
  const sig = s.signals.find((x) => x.id === s.panelId);
  const agent = sig && s.agents.find((a) => a.id === sig.agentId);
  const t = sig && signalType(sig.type);

  return (
    <SidePanel open={!!sig} onOpenChange={(o) => !o && s.setPanelId(null)}>
      <SidePanelContent overlay={false} className="w-[480px]">
        {sig && t && (
          <>
            <ModalHeader onClose={() => s.setPanelId(null)}>
              <div className="flex items-center gap-lg">
                <Avatar size="lg" shape="squared" initials={initials(sig.company)} />
                <div className="flex min-w-0 flex-col">
                  <ModalTitle>{sig.company.name}</ModalTitle>
                  <div className="flex items-center gap-sm">
                    <Button appearance="ghost" intent="brand" size="xs" leftIcon={faGlobeOutline}>{sig.company.domain}</Button>
                    <Button appearance="ghost" intent="brand" size="xs" iconOnly leftIcon={faLinkedinBrand} aria-label="Company LinkedIn" />
                  </div>
                </div>
              </div>
            </ModalHeader>
            <ModalBody>
              <div className="flex flex-col gap-xl">
                <div className="flex flex-wrap items-center gap-sm">
                  <Badge type="neutral" size="md" icon={t.icon}>{t.shortTitle}</Badge>
                  {t.isNew && <BadgeSpecific type="new">New</BadgeSpecific>}
                  <Muted>{agent?.emoji} {agent?.name} · {relTime(sig.detectedAt)}</Muted>
                </div>

                <Section icon={fa("bolt")} title="Signal details">
                  {detailRows(sig).map((r) => (
                    <Row key={r.label} label={r.label}>
                      {r.kind === "heat" ? <Heat value={Number(r.value)} />
                        : r.kind === "list" ? (
                          <ul className="flex flex-col gap-xs pl-xl [list-style:disc]">{(r.value as string[]).map((x) => <li key={x}>{x}</li>)}</ul>
                        ) : r.kind === "quote" ? <span className="block border-l-2 border-[var(--core-border-main-subtle)] pl-lg italic">“{r.value}”</span>
                        : r.kind === "link" ? <span className="flex items-center gap-xs"><Icon icon={fa("link")} size="xs" />{r.value}</span>
                        : r.value}
                    </Row>
                  ))}
                  {t.forecast && (
                    <Muted>Prediction, not a confirmed event. Generated by the forecast model from public signals; refreshed weekly.</Muted>
                  )}
                </Section>

                {sig.contact && (
                  <Section icon={fa("user")} title="Contact">
                    <div className="flex items-center gap-lg">
                      <Avatar size="md" initials={`${sig.contact.firstName[0]}${sig.contact.lastName[0]}`} />
                      <div className="flex flex-col">
                        <span className="text-base leading-base font-medium">{sig.contact.firstName} {sig.contact.lastName}</span>
                        <Muted>{sig.contact.title} · {sig.contact.location}</Muted>
                      </div>
                    </div>
                    <Row label="Email">{sig.contact.email}</Row>
                  </Section>
                )}

                <Section icon={fa("building")} title="Company" defaultOpen={!sig.contact}>
                  <div className="grid grid-cols-2 gap-lg">
                    <Row label="Industry">{sig.company.industry}</Row>
                    <Row label="Size">{sig.company.size} ({sig.company.employees} employees)</Row>
                    <Row label="Location">{sig.company.city}, {sig.company.country}</Row>
                    <Row label="Founded">{sig.company.founded}</Row>
                  </div>
                  <Row label="Description">{sig.company.description}</Row>
                </Section>
              </div>
            </ModalBody>
            <ModalFooter>
              <Button appearance="ghost" intent="brand" size="md" onClick={() => { s.setSignalStatus(sig.id, "ignored"); s.setPanelId(null); }}>Ignore</Button>
              <Button appearance="outlined" intent="brand" size="md" onClick={() => { s.setSignalStatus(sig.id, "handled"); s.toast({ type: "success", title: "Lead handled" }); }}>Mark as handled</Button>
              <Button appearance="solid" intent="brand" size="md" leftIcon={fa("paper-plane-top")} onClick={() => { s.setSignalStatus(sig.id, "handled"); s.toast({ type: "success", title: "Added to campaign", subtitle: sig.contact ? `${sig.contact.firstName} ${sig.contact.lastName}` : "Contacts sourced with your persona" }); }}>Add to campaign</Button>
            </ModalFooter>
          </>
        )}
      </SidePanelContent>
    </SidePanel>
  );
}
